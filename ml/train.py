"""Train an 8->8->1 speech-presence MLP in NumPy and export C++ weights."""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from ml.native import extract


def read_manifest(path):
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    if not rows:
        raise ValueError("Manifest is empty.")
    for field in ("speaker_id", "noise_id"):
        membership = {}
        for row in rows:
            if row["split"] not in ("train", "validation", "test"):
                raise ValueError("Unknown dataset split.")
            previous = membership.setdefault(row[field], row["split"])
            if previous != row["split"]:
                raise ValueError(f"{field} leaks across splits: {row[field]}")
    for row in rows:
        file = (path.parent/row["path"]).resolve()
        if path.parent.resolve() not in file.parents:
            raise ValueError("Dataset paths must remain inside the manifest folder.")
        if hashlib.sha256(file.read_bytes()).hexdigest() != row["sha256"]:
            raise ValueError(f"Dataset checksum mismatch: {file.name}")
    return rows


def load_split(manifest, rows, split):
    xx, yy = [], []
    for row in rows:
        if row["split"] != split:
            continue
        with np.load(manifest.parent/row["path"], allow_pickle=False) as pair:
            stereo = np.column_stack([pair["primary"], pair["reference"]])
            features = extract(stereo)
            clean = pair["clean"]
            padded = np.pad(clean, (0, (-len(clean)) % 32))
            energy = np.mean(padded.reshape(-1, 32)**2, axis=1)
            # Same 20-ms smoothing horizon as the causal features.
            smoothed = np.empty_like(energy)
            state = 0.0
            for i, value in enumerate(energy):
                state += 0.09516258*(value-state)
                smoothed[i] = state
            labels = (smoothed > 0.008**2).astype(np.float32)
            # Exclude only initial cold feature state. No future samples enter features.
            xx.append(features[10:]); yy.append(labels[10:])
    if not xx:
        raise ValueError(f"No {split} examples.")
    x, y = np.concatenate(xx).astype(np.float64), np.concatenate(yy).astype(np.float64)
    if not np.isfinite(x).all() or len(np.unique(y)) != 2:
        raise ValueError(f"{split} requires finite features and both speech/noise labels.")
    return x, y


def predict(x, parameters):
    w1, b1, w2, b2 = parameters
    h = np.tanh(x @ w1.T + b1)
    p = 1/(1+np.exp(-np.clip(h @ w2 + b2, -30, 30)))
    return h, p


def scores(x, y, parameters):
    _, p = predict(x, parameters)
    ce = -np.mean(y*np.log(p+1e-9)+(1-y)*np.log(1-p+1e-9))
    positive, actual = p >= 0.5, y > 0.5
    tp = np.sum(positive & actual)
    return {"cross_entropy": float(ce), "accuracy": float(np.mean(positive == actual)),
            "precision": float(tp/max(1, np.sum(positive))), "recall": float(tp/max(1, np.sum(actual))),
            "frames": len(y)}


def cfloat(value):
    return f"{float(value):.9e}f"


def export_header(path, model):
    w1, b1, w2, b2 = model["parameters"]
    content = "#pragma once\n// Generated by python3 -m ml.train. Match kModelId to the exported model JSON.\n"
    content += "namespace mounam::model {\ninline constexpr bool kTrained = true;\n"
    content += f'inline constexpr const char* kProvenance = "{model["provenance"]}";\n'
    content += f'inline constexpr const char* kModelId = "{model["model_id"]}";\n'
    content += "inline constexpr unsigned kInputs = 8, kHidden = 8;\n"
    content += "inline constexpr float kW1[8][8] = {\n"
    content += "".join("    {"+", ".join(cfloat(v) for v in row)+"},\n" for row in w1)+"};\n"
    content += "inline constexpr float kB1[8] = {"+", ".join(map(cfloat, b1))+"};\n"
    content += "inline constexpr float kW2[8] = {"+", ".join(map(cfloat, w2))+"};\n"
    content += "inline constexpr float kB2 = "+cfloat(b2)+";\n}\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=60)
    parser.add_argument("--seed", type=int, default=180588)
    args = parser.parse_args()
    if not 1 <= args.epochs <= 10000:
        parser.error("epochs must be 1..10000")
    rows = read_manifest(args.manifest)
    x, y = load_split(args.manifest, rows, "train")
    vx, vy = load_split(args.manifest, rows, "validation")
    rng = np.random.default_rng(args.seed)
    parameters = [rng.normal(0, 0.35, (8, 8)), np.zeros(8), rng.normal(0, 0.35, 8), np.array(0.0)]
    momentum = [np.zeros_like(p) for p in parameters]
    variance = [np.zeros_like(p) for p in parameters]
    best_loss, best, step = float("inf"), None, 0
    for epoch in range(args.epochs):
        order = rng.permutation(len(y))
        for start in range(0, len(y), 512):
            selection = order[start:start+512]
            bx, by = x[selection], y[selection]
            h, p = predict(bx, parameters)
            dz = (p-by)/len(by)
            dh = dz[:, None]*parameters[2][None, :]*(1-h*h)
            gradients = [dh.T@bx, dh.sum(axis=0), h.T@dz, dz.sum()]
            step += 1
            for i, gradient in enumerate(gradients):
                momentum[i] = 0.9*momentum[i]+0.1*gradient
                variance[i] = 0.999*variance[i]+0.001*gradient*gradient
                parameters[i] -= 0.003*(momentum[i]/(1-0.9**step))/(np.sqrt(variance[i]/(1-0.999**step))+1e-8)
        validation = scores(vx, vy, parameters)
        if validation["cross_entropy"] < best_loss:
            best_loss, best = validation["cross_entropy"], [p.copy() for p in parameters]
        if (epoch+1) % 20 == 0 or epoch == args.epochs-1:
            print(f"epoch={epoch+1} validation_cross_entropy={validation['cross_entropy']:.5f}")
    provenances = {r["provenance"] for r in rows}
    provenance = "synthetic_demo" if "synthetic_demo" in provenances else (
        "public_human_speech_generated_noise" if provenances == {"public_human_speech_generated_noise"} else "recorded_sources_synthetic_mixtures")
    model = dict(architecture="8-8-1 tanh/sigmoid float32", features="mounam-features-v1",
        provenance=provenance, seed=args.seed, epochs=args.epochs,
        manifest_sha256=hashlib.sha256(args.manifest.read_bytes()).hexdigest(),
        training=scores(x, y, best), validation=scores(vx, vy, best),
        parameters=[p.astype(np.float32).tolist() for p in best],
        limitations="Speech-presence controller; inspect provenance and the separate neural band-mask model and held-out report.")
    model["model_id"] = hashlib.sha256(json.dumps(model, sort_keys=True).encode()).hexdigest()[:16]
    args.model.parent.mkdir(parents=True, exist_ok=True)
    args.model.write_text(json.dumps(model, indent=2)+"\n")
    export_header(args.header, model)
    print(json.dumps({"model": str(args.model), "header": str(args.header), "validation": model["validation"]}, indent=2))


if __name__ == "__main__":
    main()
