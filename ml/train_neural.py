"""Train an actual eight-band mask estimator and export row-wise int8 weights."""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from ml.native import training_features, library
from ml.train import read_manifest, cfloat


def load(manifest, rows, split):
    xx, yy = [], []
    for row in rows:
        if row["split"] != split:
            continue
        with np.load(manifest.parent/row["path"], allow_pickle=False) as pair:
            x, y = training_features(np.column_stack([pair["primary"], pair["reference"]]), pair["clean"])
            xx.append(x[25::2]); yy.append(y[25::2])
    return np.concatenate(xx).astype(np.float64), np.concatenate(yy).astype(np.float64)


def predict(x, p):
    w1, b1, w2, b2 = p
    h = np.tanh(x@w1.T+b1)
    s = 1/(1+np.exp(-np.clip(h@w2.T+b2, -30, 30)))
    return h, s, 0.08+0.92*s


def quantize(weights):
    scales = np.maximum(np.max(np.abs(weights), axis=1)/127, 1e-9).astype(np.float32)
    q = np.clip(np.rint(weights/scales[:, None]), -127, 127).astype(np.int8)
    return q, scales


def quantized_predict(x, card):
    q1, q2 = np.asarray(card["q1"], float), np.asarray(card["q2"], float)
    s1, s2 = np.asarray(card["s1"]), np.asarray(card["s2"])
    h = np.tanh((x@q1.T)*s1+np.asarray(card["b1"]))
    z = (h@q2.T)*s2+np.asarray(card["b2"])
    return 0.08+0.92/(1+np.exp(-np.clip(z, -30, 30)))


def export_header(path, card):
    lines = ["#pragma once", "#include <cstdint>", "// Generated by ml.train_neural; row-wise int8 weights, float32 activations.",
        "namespace mounam::neural {", "inline constexpr bool kReady = true;",
        f'inline constexpr const char* kModelId = "{card["model_id"]}";',
        f'inline constexpr const char* kProvenance = "{card["provenance"]}";',
        "inline constexpr unsigned kInputs = 26, kHidden = 24, kOutputs = 8;",
        f'inline constexpr float kStrength = {cfloat(card.get("strength", 1.0))};']
    for key, name, shape in [("q1","kW1","24][26"),("q2","kW2","8][24")]:
        lines.append(f"inline constexpr int8_t {name}[{shape}] = {{")
        lines.extend("    {"+", ".join(str(v) for v in row)+"}," for row in card[key])
        lines.append("};")
    for key, name, length in [("s1","kS1",24),("b1","kB1",24),("s2","kS2",8),("b2","kB2",8)]:
        lines.append(f"inline constexpr float {name}[{length}] = {{"+", ".join(cfloat(v) for v in card[key])+"};")
    lines.append("}")
    path.parent.mkdir(parents=True, exist_ok=True); path.write_text("\n".join(lines)+"\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--seed", type=int, default=180588)
    args = parser.parse_args()
    if not 1 <= args.epochs <= 1000:
        parser.error("Use 1..1000 epochs.")
    rows = read_manifest(args.manifest)
    x, y = load(args.manifest, rows, "train"); vx, vy = load(args.manifest, rows, "validation")
    rng = np.random.default_rng(args.seed)
    p = [rng.normal(0,0.2,(24,26)), np.zeros(24), rng.normal(0,0.2,(8,24)), np.full(8,1.0)]
    m, v = [np.zeros_like(a) for a in p], [np.zeros_like(a) for a in p]
    best_loss, best, step = float("inf"), None, 0
    for epoch in range(args.epochs):
        order = rng.permutation(len(x))
        for start in range(0, len(x), 1024):
            sel = order[start:start+1024]; bx, by = x[sel], y[sel]
            h, s, g = predict(bx, p)
            # Extra penalty for suppressing a band whose target should remain open.
            weight = 1+2*((g < by) & (by > 0.6))
            dz = (2/(len(bx)*8))*weight*(g-by)*0.92*s*(1-s)
            dh = (dz@p[2])*(1-h*h)
            gradients = [dh.T@bx, dh.sum(0), dz.T@h, dz.sum(0)]
            step += 1
            for i, gradient in enumerate(gradients):
                m[i] = 0.9*m[i]+0.1*gradient; v[i] = 0.999*v[i]+0.001*gradient*gradient
                p[i] -= 0.002*(m[i]/(1-0.9**step))/(np.sqrt(v[i]/(1-0.999**step))+1e-8)
        _, _, vg = predict(vx, p)
        loss = float(np.mean((vg-vy)**2))
        if loss < best_loss:
            best_loss, best = loss, [a.copy() for a in p]
        if (epoch+1)%10 == 0 or epoch+1 == args.epochs:
            print(f"epoch={epoch+1} validation_band_gain_mse={loss:.6f}", flush=True)
    q1,s1=quantize(best[0]); q2,s2=quantize(best[2])
    card = dict(architecture="26-24-8 tanh/sigmoid causal band-mask MLP", provenance="public_human_speech_generated_noise",
        quantization="per-row int8 weights; float32 scales, biases and activations", seed=args.seed, epochs=args.epochs,
        q1=q1.tolist(),s1=s1.tolist(),b1=best[1].astype(np.float32).tolist(),
        q2=q2.tolist(),s2=s2.tolist(),b2=best[3].astype(np.float32).tolist(), strength=1.0,
        validation_float_mse=best_loss, manifest_sha256=hashlib.sha256(args.manifest.read_bytes()).hexdigest(),
        vad_model_id=library().mounam_model_id().decode(),
        features="eight residual powers, eight reference powers, eight log ratios, VAD, coherence; 20-ms causal EWMA",
        limits="No actual defence recordings, continuous-speech or physical-hardware validation.")
    quantized = quantized_predict(vx, card)
    card["validation_int8_mse"] = float(np.mean((quantized-vy)**2))
    card["validation_quantization_max_gain_error"] = float(np.max(np.abs(quantized-predict(vx,best)[2])))
    card["model_id"] = hashlib.sha256(json.dumps(card,sort_keys=True).encode()).hexdigest()[:16]
    args.model.parent.mkdir(parents=True,exist_ok=True); args.model.write_text(json.dumps(card,indent=2)+"\n")
    export_header(args.header,card)
    print(json.dumps({k:card[k] for k in ["model_id","validation_float_mse","validation_int8_mse","validation_quantization_max_gain_error"]},indent=2))


if __name__ == "__main__":
    main()
